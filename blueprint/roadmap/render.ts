/*
	Renders README.md from milestones.json and issues.json.

	The JSON is canonical — it is what `gh` imports — and the markdown is a view
	of it. Writing both by hand would put the blueprint in the position it spends
	ten guides telling you to avoid.

	    bun blueprint/roadmap/render.ts
*/
import fs from 'node:fs';
import path from 'node:path';

interface Milestone {
	title: string;
	description: string;
	state: string;
}
interface Issue {
	title: string;
	milestone: string;
	labels: string[];
	body: string;
}

const here = import.meta.dirname;
const milestones: Milestone[] = JSON.parse(
	fs.readFileSync(path.join(here, 'milestones.json'), 'utf8')
);
const issues: Issue[] = JSON.parse(fs.readFileSync(path.join(here, 'issues.json'), 'utf8'));

const byMilestone = new Map<string, Issue[]>();
for (const issue of issues) {
	byMilestone.set(issue.milestone, [...(byMilestone.get(issue.milestone) ?? []), issue]);
}

const orphans = [...byMilestone.keys()].filter((name) => !milestones.some((m) => m.title === name));
if (orphans.length) {
	throw new Error(`issues.json references unknown milestones: ${orphans.join(', ')}`);
}

const lines: string[] = [];

lines.push('# Roadmap');
lines.push('');
lines.push('<!-- Generated by render.ts from milestones.json and issues.json. Do not edit. -->');
lines.push('');
lines.push(
	`${milestones.length} milestones, ${issues.length} issues. Version numbers are projected, ` +
		'not promised — they exist so the milestones have a shape.'
);
lines.push('');
lines.push('To put this into a GitHub repository, see [IMPORT.md](IMPORT.md).');
lines.push('');
lines.push('---');
lines.push('');

lines.push('## At a glance');
lines.push('');
lines.push('| Milestone | Issues | Theme |');
lines.push('| --- | --- | --- |');
for (const milestone of milestones) {
	const count = (byMilestone.get(milestone.title) ?? []).length;
	const anchor = milestone.title
		.toLowerCase()
		.replace(/[^\w\s-]/g, '')
		.replace(/\s+/g, '-');
	lines.push(`| [${milestone.title}](#${anchor}) | ${count} | ${milestone.description} |`);
}
lines.push('');
lines.push('---');
lines.push('');

for (const milestone of milestones) {
	const own = byMilestone.get(milestone.title) ?? [];
	lines.push(`## ${milestone.title}`);
	lines.push('');
	lines.push(`> ${milestone.description}`);
	lines.push('');
	if (!own.length) {
		lines.push('_No issues yet._');
		lines.push('');
		continue;
	}
	lines.push('| # | Issue | Labels |');
	lines.push('| --- | --- | --- |');
	own.forEach((issue, index) => {
		lines.push(`| ${index + 1} | **${issue.title}** | ${issue.labels.join(', ')} |`);
	});
	lines.push('');
	for (const issue of own) {
		lines.push(`### ${issue.title}`);
		lines.push('');
		lines.push(`\`${issue.labels.join('` `')}\``);
		lines.push('');
		lines.push(issue.body);
		lines.push('');
	}
	lines.push('---');
	lines.push('');
}

lines.push('## Labels used');
lines.push('');
const labels = [...new Set(issues.flatMap((i) => i.labels))].sort();
lines.push('| Label | Issues |');
lines.push('| --- | --- |');
for (const label of labels) {
	lines.push(`| \`${label}\` | ${issues.filter((i) => i.labels.includes(label)).length} |`);
}
lines.push('');

fs.writeFileSync(path.join(here, 'README.md'), lines.join('\n'), 'utf8');
console.log(
	`roadmap: ${milestones.length} milestones, ${issues.length} issues, ${labels.length} labels -> README.md`
);
